CREATE TABLE it_services (
    id UUID PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(1000) NOT NULL,
    business_criticality INTEGER NOT NULL CHECK (business_criticality BETWEEN 1 AND 3),
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX it_services_name_unique ON it_services(lower(name));
CREATE TABLE incident_categories (
    id UUID PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(1000) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX incident_categories_name_unique ON incident_categories(lower(name));
CREATE TABLE incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    title VARCHAR(200) NOT NULL,
    description VARCHAR(10000) NOT NULL,
    reporter_id UUID NOT NULL REFERENCES users(id),
    service_id UUID NOT NULL REFERENCES it_services(id),
    category_id UUID NOT NULL REFERENCES incident_categories(id),
    impact INTEGER NOT NULL CHECK (impact BETWEEN 1 AND 3),
    urgency INTEGER NOT NULL CHECK (urgency BETWEEN 1 AND 3),
    priority VARCHAR(2) CHECK (priority IN ('P1','P2','P3','P4')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('NEW','CLASSIFIED','ASSIGNED','ACKNOWLEDGED','IN_PROGRESS','RESOLVED','VERIFIED','CLOSED')),
    technician_id UUID REFERENCES users(id),
    resolution VARCHAR(10000),
    feedback VARCHAR(2000),
    feedback_rating INTEGER CHECK (feedback_rating BETWEEN 1 AND 5),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    acknowledged_at TIMESTAMP WITH TIME ZONE,
    resolved_at TIMESTAMP WITH TIME ZONE,
    verified_at TIMESTAMP WITH TIME ZONE,
    closed_at TIMESTAMP WITH TIME ZONE,
    CHECK (status IN ('NEW','CLASSIFIED') OR technician_id IS NOT NULL),
    CHECK (status NOT IN ('RESOLVED','VERIFIED','CLOSED') OR resolution IS NOT NULL),
    CHECK (status NOT IN ('VERIFIED','CLOSED') OR verified_at IS NOT NULL),
    CHECK (status <> 'CLOSED' OR closed_at IS NOT NULL)
);
CREATE INDEX incidents_reporter_idx ON incidents(reporter_id, created_at DESC);
CREATE INDEX incidents_technician_idx ON incidents(technician_id, status);
CREATE INDEX incidents_status_idx ON incidents(status);
CREATE INDEX incidents_category_idx ON incidents(category_id);
CREATE INDEX incidents_service_idx ON incidents(service_id);
CREATE INDEX incidents_created_idx ON incidents(created_at DESC);
CREATE TABLE incident_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT NOT NULL REFERENCES incidents(id),
    author_id UUID NOT NULL REFERENCES users(id),
    body VARCHAR(5000) NOT NULL,
    internal BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX incident_comments_incident_idx ON incident_comments(incident_id,id);
CREATE TABLE incident_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT NOT NULL REFERENCES incidents(id),
    actor_id UUID NOT NULL REFERENCES users(id),
    action VARCHAR(40) NOT NULL,
    previous_status VARCHAR(20),
    new_status VARCHAR(20) NOT NULL,
    description TEXT NOT NULL,
    internal BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX incident_history_incident_idx ON incident_history(incident_id,id);
