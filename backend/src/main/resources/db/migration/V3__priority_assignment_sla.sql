CREATE TABLE technician_skills (
    user_id UUID NOT NULL REFERENCES technician_profiles(user_id),
    category_id UUID NOT NULL REFERENCES incident_categories(id),
    proficiency INTEGER NOT NULL CHECK (proficiency BETWEEN 1 AND 3),
    PRIMARY KEY(user_id,category_id)
);
CREATE TABLE sla_policies (
    id UUID PRIMARY KEY,
    service_id UUID REFERENCES it_services(id),
    priority VARCHAR(2) NOT NULL CHECK (priority IN ('P1','P2','P3','P4')),
    response_seconds INTEGER NOT NULL CHECK (response_seconds BETWEEN 1 AND 31536000),
    resolution_seconds INTEGER NOT NULL CHECK (resolution_seconds BETWEEN response_seconds AND 31536000),
    warning_percent INTEGER NOT NULL CHECK (warning_percent BETWEEN 1 AND 99),
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX sla_global_priority_unique ON sla_policies(priority) WHERE service_id IS NULL;
CREATE UNIQUE INDEX sla_service_priority_unique ON sla_policies(service_id,priority) WHERE service_id IS NOT NULL;
